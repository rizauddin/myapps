// Keep the upstream font and rendering rules, selecting only icons used by the app.
// Run npm run icons:update after adding literal bi-* classes. For constructed class
// names, add every possible value to additionalIcons before regenerating.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const additionalIcons = [];
const names = new Set(additionalIcons);
function visit(directory) {
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    const file = path.join(directory, entry.name);
    if (entry.isDirectory()) visit(file);
    else if (/\.(html|ts)$/.test(file) && !file.endsWith('.spec.ts')) {
      for (const match of fs.readFileSync(file, 'utf8').matchAll(/\bbi-[a-z0-9-]+\b/g)) names.add(match[0]);
    }
  }
}
visit(path.join(root, 'src'));
const upstream = fs.readFileSync(path.join(root, 'node_modules/bootstrap-icons/font/bootstrap-icons.css'), 'utf8');
const rules = new Map([...upstream.matchAll(/\.(bi-[a-z0-9-]+)::before\s*\{[^}]+\}/g)].map(match => [match[1], match[0]]));
const selected = [...names].sort().map(name => {
  if (!rules.has(name)) throw new Error(`Unknown Bootstrap icon: ${name}`);
  return rules.get(name);
});
const preamble = upstream.slice(0, upstream.indexOf('.bi-123::before'))
  .replaceAll('./fonts/', '../node_modules/bootstrap-icons/font/fonts/');
const output = '/* Generated by scripts/generate-bootstrap-icons.cjs; do not edit. */\n' + preamble + selected.join('\n') + '\n';
const target = path.join(root, 'src/bootstrap-icons.css');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== output) throw new Error('Icon CSS is stale. Run npm run icons:update.');
} else fs.writeFileSync(target, output);
console.log(`Bootstrap Icons: ${names.size} original glyph rules retained.`);
